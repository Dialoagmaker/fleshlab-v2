function chooseLanguage(metadata, analysis) {
  const text = textFrom(metadata);
  if (/beach|escape|summer|island|outdoor|travel|vacation|cebu|sea|pool/.test(text)) return LANGUAGES.vacation;
  if (/hotel|bareback|night|secret|forbidden|private|dark|room|danger/.test(text)) return LANGUAGES.danger;
  if (/massage|spa|luxury|premium|vip|suite|gentle|sensual/.test(text)) return LANGUAGES.luxury;
  if (/first|debut|documentary|behind|real|honest|story/.test(text)) return LANGUAGES.documentary;
  if (/fan favorite|favorite|fans|celebration|popular|viral|community/.test(text)) return LANGUAGES.celebration;
  if (/raw|amateur|uncut|rough|wild|homemade/.test(text)) return LANGUAGES.raw;
  if ((analysis?.brightness || 0.5) < 0.36) return LANGUAGES.danger;
  return DEFAULT_LANGUAGE;
}

export function inferGraphicLanguage(metadata = {}, analysis = {}) {
  const language = { ...DEFAULT_LANGUAGE, ...chooseLanguage(metadata, analysis) };
  const specificity = language.id === DEFAULT_LANGUAGE.id ? 0.58 : 0.86;
  const visualFit = clamp((analysis.thumbnailImpact || 0.55) * 0.28 + (analysis.sceneReadability || 0.55) * 0.22 + (analysis.visualCuriosity || 0.55) * 0.18 + specificity * 0.32);
  return {
    ...language,
    score: Math.round(visualFit * 100),
    strength: visualFit,
    validation: {
      canSpeakWithoutText: visualFit >= 0.58,
      emotionalGenreWithin500ms: language.id !== DEFAULT_LANGUAGE.id || visualFit >= 0.66,
      failures: [
        ...(visualFit < 0.58 ? ["graphic language too weak without title"] : []),
        ...(language.id === DEFAULT_LANGUAGE.id && visualFit < 0.66 ? ["commercial promise did not select a distinct visual identity"] : []),
      ],
    },
  };
}

export function applyGraphicLanguageToFamily(family, graphicLanguage) {
  if (!family || !graphicLanguage) return family;
  return {
    ...family,
    graphicLanguage,
    cropZoom: (family.cropZoom || 1) * (graphicLanguage.cropZoomMultiplier || 1),
    treatment: graphicLanguage.atmosphere || family.treatment,
    typography: {
      ...family.typography,
      titleFont: graphicLanguage.titleFont || family.typography?.titleFont,
      accentFont: graphicLanguage.accentFont || family.typography?.accentFont,
      titleScale: (family.typography?.titleScale || 0.08) * (graphicLanguage.titleScaleMultiplier || 1),
    },
  };
}