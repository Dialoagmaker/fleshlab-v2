function clamp(value, min = 0, max = 1) {
  return Math.max(min, Math.min(max, value));
}

function textFrom(metadata = {}) {
  return [metadata.videoTitle, metadata.optionalSubtitle, metadata.campaignName, metadata.contentType, metadata.performerName]
    .filter(Boolean)
    .join(" ")
    .toLowerCase();
}

